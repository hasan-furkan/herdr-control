"""Pack mods/herdr-control/collector/collect.py into mods/herdr-control/collector/packed.js.

The mod sends the collector to machines as `python -I -c <bootstrap>`.
The bootstrap carries the minified, LZMA-compressed source to fit the Windows
command line. Run after every change to collect.py: py -3 scripts/pack-collector.py
"""
import ast
import base64
import hashlib
import json
import lzma
import pathlib


TARGET_BOOTSTRAP_CHARS = 26_000
MAX_BOOTSTRAP_CHARS = 30_000
BMP_PAYLOAD_START = 0x4E00


def minify_source(src):
    tree = ast.parse(src, feature_version=(3, 9))
    for node in ast.walk(tree):
        if not isinstance(node, (ast.Module, ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)):
            continue
        if ast.get_docstring(node, clean=False) is None:
            continue
        del node.body[0]
        if not node.body and not isinstance(node, ast.Module):
            node.body.append(ast.Pass())
    return ast.unparse(tree).encode("utf-8")


def build_bootstrap(src):
    filters = [{"id": lzma.FILTER_LZMA2, "preset": 9, "dict_size": 1 << 20}]
    compressed = lzma.compress(minify_source(src), filters=filters)
    # Check isolation before loading the payload. Arguments after -c pass through.
    guard = "import sys;sys.flags.isolated or sys.exit('collector requires python -I');"
    execute = "exec(compile(lzma.decompress(blob),'collect.py','exec'),{'__name__':'__main__'})"
    ascii_payload = base64.b85encode(compressed).decode("ascii")
    boot = f"{guard}import base64,lzma;blob=base64.b85decode('{ascii_payload}');{execute}"
    if len(boot) >= TARGET_BOOTSTRAP_CHARS:
        boot = f"{guard}import lzma;{compact_payload(compressed)}{execute}"
    if len(boot) > MAX_BOOTSTRAP_CHARS:
        raise SystemExit(f"bootstrap too long for Windows: {len(boot)} chars")
    return boot


def compact_payload(compressed):
    # Two BMP characters carry three bytes. These code points each use one
    # Windows UTF-16 code unit and avoid quotes, whitespace, and surrogates.
    padded = compressed + bytes(-len(compressed) % 3)
    groups = (int.from_bytes(padded[i:i + 3], "big") for i in range(0, len(padded), 3))
    payload = "".join(
        chr(BMP_PAYLOAD_START + (value >> 12)) + chr(BMP_PAYLOAD_START + (value & 0xFFF))
        for value in groups
    )
    return (
        f"payload='{payload}';"
        "blob=b''.join("
        f"(((ord(a)-{BMP_PAYLOAD_START})<<12)|(ord(b)-{BMP_PAYLOAD_START})).to_bytes(3,'big') "
        f"for a,b in zip(payload[::2],payload[1::2]))[:{len(compressed)}];"
    )


def main():
    root = pathlib.Path(__file__).resolve().parent.parent
    src = (root / "mods/herdr-control/collector/collect.py").read_bytes()
    boot = build_bootstrap(src)
    out = root / "mods/herdr-control/collector/packed.js"
    out.write_bytes((
        "// Generated by scripts/pack-collector.py from collect.py. Do not edit.\n"
        f"// sha256 of the source: {hashlib.sha256(src).hexdigest()}\n"
        'export const COLLECTOR_PYTHON_FLAGS = Object.freeze(["-I"]);\n'
        f"export const COLLECTOR_BOOTSTRAP = {json.dumps(boot, ensure_ascii=False)};\n"
    ).encode("utf-8"))
    print(f"packed {len(src)} bytes -> bootstrap {len(boot)} chars")


if __name__ == "__main__":
    main()
